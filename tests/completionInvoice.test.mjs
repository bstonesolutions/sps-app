test("one-off completion creates one deterministic draft with service, billable parts, and billable products", () => {
  const stop = { sid: "repair-1", clientId: "client-1", type: "Repair Visit" };
  const entry = {
    sid: stop.sid,
    completionReceiptId: "receipt-repair-1",
    services: [{ id: "svc-repair", name: "Repair labor", price: "175", cost: "60" }],
    invoice: "$175.00",
    partsUsed: [
      { id: "part-valve", name: "Valve", qty: 2, unit: "pieces", retailPer: 25, costPer: 10, bill: true },
      { id: "part-shop", name: "Shop supply", qty: 1, retailPer: 5, costPer: 2, bill: false },
    ],
    productsPurchased: [
      { id: "product-skimmer", name: "Skimmer plate", qty: 1, price: 79.99, cost: 35, bill: true },
      { id: "product-warranty", name: "Warranty replacement", qty: 1, price: 20, cost: 20, bill: false },
    ],
  };
  const existingInvoices = [{ id: "old", number: "INV-2004" }];
  const result = planCompletionInvoice({
    invoices: existingInvoices,
    invoicing,
    schedule: [{ date: "08/03/2026", stops: [stop] }],
    completed: { [stop.sid]: marker(entry.completionReceiptId) },
    stop,
    entry,
    client: baseClient(),
    receiptId: entry.completionReceiptId,
    completedAt: "2026-08-03T14:00:00.000Z",
    now: Date.parse("2026-08-03T14:00:00.000Z"),
  });

  assert.equal(result.changed, true);
  assert.deepEqual(result.outcome, {
    status: "created",
    kind: "one-off",
    invoiceId: "iv_stop_repair-1",
    invoiceNumber: "INV-2005",
    sourceStopId: "repair-1",
  });
  assert.equal(result.invoices.length, 2);
  assert.equal(existingInvoices.length, 1, "the source array remains unchanged");
  const invoice = result.invoices[0];
  assert.equal(invoice.status, "Draft");
  assert.equal(invoice.source, "completed-stop");
  assert.equal(invoice.sourceStopId, stop.sid);
  assert.equal(invoice.sourceCompletionReceiptId, entry.completionReceiptId);
  assert.equal(invoice.date, "08/03/2026");
  assert.equal(invoice.dueDate, "08/18/2026");
  assert.equal(invoice.taxRate, "6");
  assert.equal(invoice.qbSyncStatus, "local");
  assert.equal(invoice.autoGeneratedBy, "stop-completion");
  assert.equal(invoice.autoDraftFingerprint, completionInvoiceFingerprint(invoice));
  assert.deepEqual(
    invoice.lineItems.map(({ desc, qty, unitPrice, unitCost, taxable, kind, refId }) => ({
      desc, qty, unitPrice, unitCost, taxable, kind, refId,
    })),
    [
      { desc: "Repair labor", qty: "1", unitPrice: "175", unitCost: "60", taxable: false, kind: "service", refId: "svc-repair" },
      { desc: "Valve", qty: "2", unitPrice: "25", unitCost: "10", taxable: true, kind: "part", refId: "part-valve" },
      { desc: "Skimmer plate", qty: "1", unitPrice: "79.99", unitCost: "35", taxable: true, kind: "product", refId: "product-skimmer" },
    ],
  );
});

