for (const frequency of ["Weekly", "Bi-Weekly"]) {
  test(`${frequency} maintenance waits for the final non-cancelled stop, then creates one monthly draft`, () => {
    const prefix = frequency === "Weekly" ? "weekly" : "biweekly";
    const firstStop = { sid: `${prefix}-1`, clientId: "client-1", type: `${frequency} Service` };
    const finalStop = { sid: `${prefix}-2`, clientId: "client-1", type: `${frequency} Service` };
    const cancelledStop = { sid: `${prefix}-cancelled`, clientId: "client-1", type: `${frequency} Service`, cancelled: true };
    const otherMonthStop = { sid: `${prefix}-september`, clientId: "client-1", type: `${frequency} Service` };
    const oneOffRepair = { sid: `${prefix}-repair`, clientId: "client-1", type: "Repair Visit" };
    const schedule = [
      { date: "08/03/2026", stops: [firstStop] },
      { date: "08/17/2026", stops: [finalStop] },
      { date: "08/24/2026", stops: [cancelledStop] },
      { date: "08/25/2026", stops: [oneOffRepair] },
      { date: "09/01/2026", stops: [otherMonthStop] },
    ];
    const firstEntry = {
      sid: firstStop.sid,
      completionReceiptId: `receipt-${prefix}-1`,
      partsUsed: [{ id: "part-valve", name: "Valve", qty: 1, unit: "piece", retailPer: 20, costPer: 8, bill: true }],
      productsPurchased: [{ id: "product-bacteria", name: "Bacteria", qty: 1, price: 15, cost: 5, bill: true }],
    };
    const finalEntry = {
      sid: finalStop.sid,
      completionReceiptId: `receipt-${prefix}-2`,
      partsUsed: [
        { id: "part-valve", name: "Valve", qty: 2, unit: "piece", retailPer: 20, costPer: 8, bill: true },
        { id: "part-included", name: "Included part", qty: 1, retailPer: 99, costPer: 10, bill: false },
      ],
      productsPurchased: [{ id: "product-bacteria", name: "Bacteria", qty: 2, price: 15, cost: 5, bill: true }],
    };
    const client = baseClient({
      planFreq: frequency,
      monthlyRate: "600",
      history: [firstEntry],
    });

    const beforeFinal = planCompletionInvoice({
      invoices: [],
      invoicing,
      schedule,
      completed: { [firstStop.sid]: marker(firstEntry.completionReceiptId) },
      stop: firstStop,
      entry: firstEntry,
      client,
      receiptId: firstEntry.completionReceiptId,
      completedAt: "2026-08-03T14:00:00.000Z",
    });
    assert.equal(beforeFinal.changed, false);
    assert.equal(beforeFinal.outcome.status, "pending");
    assert.deepEqual(beforeFinal.outcome.remainingStopIds, [finalStop.sid]);
    assert.equal(beforeFinal.outcome.visitCount, 2, "cancelled, repair, and other-month stops do not block the period");

    const afterFinal = planCompletionInvoice({
      invoices: [],
      invoicing,
      schedule,
      completed: {
        [firstStop.sid]: marker(firstEntry.completionReceiptId),
        [finalStop.sid]: marker(finalEntry.completionReceiptId),
        [otherMonthStop.sid]: marker(`receipt-${prefix}-september`),
      },
      stop: finalStop,
      entry: finalEntry,
      client,
      receiptId: finalEntry.completionReceiptId,
      completedAt: "2026-08-17T14:00:00.000Z",
      now: Date.parse("2026-08-17T14:00:00.000Z"),
    });

    assert.equal(afterFinal.changed, true);
    assert.equal(afterFinal.outcome.status, "created");
    assert.equal(afterFinal.outcome.kind, "monthly");
    assert.equal(afterFinal.outcome.period, "2026-08");
    assert.equal(afterFinal.outcome.visitCount, 2);
    const invoice = afterFinal.invoices[0];
    assert.equal(invoice.id, "iv_maint_client-1_2026-08");
    assert.equal(invoice.source, "monthly-maintenance");
    assert.equal(invoice.autoPeriod, "2026-08");
    assert.deepEqual(invoice.sourceStopIds, [firstStop.sid, finalStop.sid]);
    assert.deepEqual(invoice.sourceCompletionReceiptIds, [firstEntry.completionReceiptId, finalEntry.completionReceiptId]);
    assert.deepEqual(
      invoice.lineItems.map(({ desc, qty, unitPrice, kind }) => ({ desc, qty, unitPrice, kind })),
      [
        { desc: "Monthly service — August 2026", qty: "1", unitPrice: "600", kind: "service" },
        { desc: "Valve", qty: "3", unitPrice: "20", kind: "part" },
        { desc: "Bacteria", qty: "3", unitPrice: "15", kind: "product" },
      ],
    );

    const replay = planCompletionInvoice({
      invoices: afterFinal.invoices,
      invoicing,
      schedule,
      completed: {
        [firstStop.sid]: marker(firstEntry.completionReceiptId),
        [finalStop.sid]: marker(finalEntry.completionReceiptId),
      },
      stop: finalStop,
      entry: finalEntry,
      client,
    });
    assert.equal(replay.changed, false);
    assert.equal(replay.invoices.length, 1);
    assert.equal(replay.outcome.status, "existing");
    assert.equal(replay.outcome.invoiceId, invoice.id);
  });
}

test("a later same-month completion rebuilds only an untouched monthly auto-draft", () => {
  const firstStop = { sid: "monthly-later-1", clientId: "client-1", type: "Weekly Service" };
  const laterStop = { sid: "monthly-later-2", clientId: "client-1", type: "Weekly Service" };
  const firstEntry = {
    sid: firstStop.sid,
    completionReceiptId: "receipt-monthly-later-1",
    productsPurchased: [{ id: "bacteria", name: "Bacteria", qty: 1, price: 15, cost: 5, bill: true }],
  };
  const laterEntry = {
    sid: laterStop.sid,
    completionReceiptId: "receipt-monthly-later-2",
    productsPurchased: [{ id: "bacteria", name: "Bacteria", qty: 2, price: 15, cost: 5, bill: true }],
    partsUsed: [{ id: "valve", name: "Valve", qty: 1, retailPer: 20, costPer: 8, bill: true }],
  };
  const client = baseClient({ planFreq: "Weekly", monthlyRate: "400", history: [firstEntry] });
  const first = planCompletionInvoice({
    invoices: [],
    invoicing,
    schedule: [{ date: "08/03/2026", stops: [firstStop] }],
    completed: { [firstStop.sid]: marker(firstEntry.completionReceiptId) },
    stop: firstStop,
    entry: firstEntry,
    client,
    completedAt: "2026-08-03T14:00:00.000Z",
    now: Date.parse("2026-08-03T14:00:00.000Z"),
  });
  const original = first.invoices[0];

  const laterInput = {
    invoices: first.invoices,
    invoicing,
    schedule: [
      { date: "08/03/2026", stops: [firstStop] },
      { date: "08/17/2026", stops: [laterStop] },
    ],
    completed: {
      [firstStop.sid]: marker(firstEntry.completionReceiptId),
      [laterStop.sid]: marker(laterEntry.completionReceiptId),
    },
    stop: laterStop,
    entry: laterEntry,
    client,
    completedAt: "2026-08-17T14:00:00.000Z",
    now: Date.parse("2026-08-17T14:00:00.000Z"),
  };
  const updated = planCompletionInvoice(laterInput);

  assert.equal(updated.changed, true);
  assert.deepEqual(updated.outcome, {
    status: "updated",
    kind: "monthly",
    period: "2026-08",
    invoiceId: original.id,
    invoiceNumber: original.number,
    visitCount: 2,
  });
  const rebuilt = updated.invoices[0];
  assert.equal(rebuilt.id, original.id);
  assert.equal(rebuilt.number, original.number);
  assert.equal(rebuilt.date, original.date);
  assert.equal(rebuilt.createdAt, original.createdAt);
  assert.deepEqual(rebuilt.sourceStopIds, [firstStop.sid, laterStop.sid]);
  assert.deepEqual(
    rebuilt.lineItems.map(({ desc, qty, unitPrice, kind }) => ({ desc, qty, unitPrice, kind })),
    [
      { desc: "Monthly service — August 2026", qty: "1", unitPrice: "400", kind: "service" },
      { desc: "Bacteria", qty: "3", unitPrice: "15", kind: "product" },
      { desc: "Valve", qty: "1", unitPrice: "20", kind: "part" },
    ],
  );
  assert.equal(rebuilt.autoDraftFingerprint, completionInvoiceFingerprint(rebuilt));

  const replay = planCompletionInvoice({ ...laterInput, invoices: updated.invoices });
  assert.equal(replay.changed, false);
  assert.equal(replay.invoices, updated.invoices);
  assert.equal(replay.outcome.status, "existing");

  const protectedVariants = [
    { ...original, status: "Sent" },
    { ...original, qbId: "qb-monthly-later" },
    { ...original, lineItems: original.lineItems.map((line, index) => (
      index === 0 ? { ...line, unitPrice: "425" } : line
    )) },
  ];
  for (const protectedInvoice of protectedVariants) {
    const protectedResult = planCompletionInvoice({ ...laterInput, invoices: [protectedInvoice] });
    assert.equal(protectedResult.changed, false);
    assert.equal(protectedResult.invoices[0], protectedInvoice);
    assert.equal(protectedResult.outcome.status, "existing");
  }
});

